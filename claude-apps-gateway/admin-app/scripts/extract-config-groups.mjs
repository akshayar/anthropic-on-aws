#!/usr/bin/env node
/**
 * Extract IdP group names declared in the gateway config into a static JS module
 * (src/configGroups.js) so the admin UI can suggest groups that have no spend yet.
 *
 * WHY THIS EXISTS: the gateway exposes NO config/policies read endpoint (only
 * spend_limits, health, discovery, and the per-group-gated /user/bootstrap). The
 * only source of truth for "which groups exist" is the config YAML itself. The
 * live /effective telemetry only knows groups that have already generated spend,
 * so a brand-new group (e.g. a team just added to the config) would never appear
 * in the group-cap picker. This bakes the declared groups in at build time.
 *
 * It parses, without a YAML dependency:
 *   - every `match: { groups: [a, b] }` in managed.policies
 *   - `admin_groups: [x, y]` in the admin block
 *
 * Source config resolution order:
 *   1. $GATEWAY_CONFIG env var (an explicit path)
 *   2. ../../cdk/gateway.yaml         (the stamped, deployed config, if present)
 *   3. ../../cdk/gateway.yaml.template (checked-in template — always present)
 *
 * Run manually (`node scripts/extract-config-groups.mjs`) or via `npm run build`,
 * which runs it first. Safe to re-run; output is deterministic and sorted.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const cdkDir = resolve(__dirname, '..', '..', 'cdk')

function pickConfigPath() {
  if (process.env.GATEWAY_CONFIG && existsSync(process.env.GATEWAY_CONFIG)) {
    return process.env.GATEWAY_CONFIG
  }
  const stamped = resolve(cdkDir, 'gateway.yaml')
  if (existsSync(stamped)) return stamped
  const template = resolve(cdkDir, 'gateway.yaml.template')
  if (existsSync(template)) return template
  return null
}

/** Pull the bracketed list after a `key:` into an array of trimmed names. */
function bracketList(text, key) {
  const out = []
  // Matches `<key>: [a, b, c]` (also inside inline `{ ... }` blocks).
  const re = new RegExp(`${key}\\s*:\\s*\\[([^\\]]*)\\]`, 'g')
  let m
  while ((m = re.exec(text)) !== null) {
    for (const raw of m[1].split(',')) {
      const name = raw.trim().replace(/^['"]|['"]$/g, '')
      // Skip empties and the catch-all `match: {}` (which has no groups list at all,
      // so it never reaches here) and any templating placeholder.
      if (name && !name.startsWith('@@') && !name.startsWith('${')) out.push(name)
    }
  }
  return out
}

const configPath = pickConfigPath()
const outPath = resolve(__dirname, '..', 'src', 'configGroups.js')

if (!configPath) {
  // No config reachable — this happens inside the Docker build, whose context is
  // only admin-app/ (the cdk/ config lives outside it). Do NOT clobber an
  // already-generated configGroups.js with an empty list: the committed file
  // (generated at commit time from the real config) is what should ship. Only
  // write a fresh empty stub if none exists at all.
  if (existsSync(outPath)) {
    console.warn('[extract-config-groups] no gateway config reachable; keeping existing src/configGroups.js')
    process.exit(0)
  }
  console.warn('[extract-config-groups] no gateway config reachable and no existing list; writing empty stub')
}

const text = configPath ? readFileSync(configPath, 'utf8') : ''
const groups = new Set([
  ...bracketList(text, 'groups'),
  ...bracketList(text, 'admin_groups'),
])
const sorted = [...groups].sort()

const banner = `// AUTO-GENERATED by scripts/extract-config-groups.mjs — do not edit by hand.\n`
  + `// Source: ${configPath ? configPath.replace(cdkDir, 'cdk') : '(none found)'}\n`
  + `// Declared IdP groups from the gateway config, so the group-cap picker can\n`
  + `// suggest groups that have not generated any spend yet.\n`
writeFileSync(outPath, `${banner}export const CONFIG_GROUPS = ${JSON.stringify(sorted)}\n`)

console.log(`[extract-config-groups] wrote ${sorted.length} group(s) to src/configGroups.js: ${sorted.join(', ') || '(none)'}`)
